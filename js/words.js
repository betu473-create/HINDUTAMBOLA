try{
  var _jtSaved = JSON.parse(localStorage.getItem('jt_word_list') || 'null');
  if(Array.isArray(_jtSaved) && _jtSaved.length){
    SHABD_LIST.splice(0, SHABD_LIST.length);
    _jtSaved.forEach(function(w){ SHABD_LIST.push(String(w)); });
    jtCustomList = true;
  }
}catch(e){}
window.JT_PACK_OK = !jtCustomList;

